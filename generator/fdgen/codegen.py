"""Emit plain C for all element types plus a small registry the runtime links against."""

from pathlib import Path

import casadi as ca

from . import forces, joints, rigid_body
from .lagrange import ROLES as FUNCTION_ROLES

# All element types known to the generator. The runtime is compiled with all of them.
ELEMENT_BUILDERS = {"rigid_body": rigid_body.build, "rigid_body_euler": rigid_body.build_euler}
for _mod in (joints, forces):
    for _kind in _mod.KINDS:
        ELEMENT_BUILDERS[_kind] = lambda k=_kind, m=_mod: m.build(k)
        ELEMENT_BUILDERS[_kind + "_euler"] = lambda k=_kind, m=_mod: m.build_euler(k)

# Version of the layout below; a model plugin is only loaded by a runtime with the same one.
REGISTRY_ABI = 2

_REGISTRY_H = """\
/* Generated by fdgen. Do not edit. */
#ifndef {guard}
#define {guard}

{includes}

/* Layout version of fd_function / fd_element_type and the role order. */
#define FD_REGISTRY_ABI "{abi}"

#ifdef __cplusplus
extern "C" {{
#endif

/* Function table of one CasADi-generated function. */
typedef struct {{
  const char* name;
  int (*eval)(const casadi_real** arg, casadi_real** res, casadi_int* iw, casadi_real* w, int mem);
  int (*work)(casadi_int* sz_arg, casadi_int* sz_res, casadi_int* sz_iw, casadi_int* sz_w);
  casadi_int (*n_in)(void);
  casadi_int (*n_out)(void);
  const casadi_int* (*sparsity_in)(casadi_int i);
  const casadi_int* (*sparsity_out)(casadi_int i);
  const char* (*name_out)(casadi_int i);
}} fd_function;

/* All functions of one element type; roles the type does not provide have eval == NULL. */
typedef struct {{
  const char* name;
  fd_function {roles};
}} fd_element_type;

{externs}

#ifdef __cplusplus
}} /* extern "C" */
#endif

#endif
"""


def _fun_entry(fname):
    return (
        f'{{"{fname}", {fname}, {fname}_work, {fname}_n_in, {fname}_n_out, '
        f"{fname}_sparsity_in, {fname}_sparsity_out, {fname}_name_out}}"
    )


def write_registry(outdir, elements, plugin=False):
    """Registry header and source for [(type name, ElementFunctions)] in outdir.

    The built-in registry exports fd_element_types / fd_n_element_types; a model plugin
    exports fd_plugin_element_types / fd_plugin_n_element_types and fd_plugin_abi(), which the
    runtime compares with its own FD_REGISTRY_ABI before using the plugin."""
    outdir = Path(outdir)
    pre = "fd_plugin_" if plugin else "fd_"
    stem = "fd_plugin" if plugin else "fd_registry"
    entries = []
    for name, elem in elements:
        funs = ",\n    ".join(
            _fun_entry(f"fd_{name}_{role}") if role in elem.funs else "{0}" for role in FUNCTION_ROLES)
        entries.append(f'  {{"{name}",\n    {funs}}}')
    externs = (f"extern const fd_element_type {pre}element_types[];\n"
               f"extern const int {pre}n_element_types;")
    if plugin:
        externs += "\nconst char* fd_plugin_abi(void);"
    includes = "\n".join(f'#include "{n}.h"' for n, _ in elements)
    abi = f"{REGISTRY_ABI} " + " ".join(FUNCTION_ROLES)
    (outdir / f"{stem}.h").write_text(encoding="utf-8", data=_REGISTRY_H.format(
        guard=stem.upper() + "_H", includes=includes, abi=abi, roles=", ".join(FUNCTION_ROLES), externs=externs))
    body = ("/* Generated by fdgen. Do not edit. */\n"
            f'#include "{stem}.h"\n\n'
            f"const fd_element_type {pre}element_types[] = {{\n" + ",\n".join(entries) + "\n};\n"
            f"const int {pre}n_element_types = {len(entries)};\n")
    if plugin:
        body += "const char* fd_plugin_abi(void) { return FD_REGISTRY_ABI; }\n"
    (outdir / f"{stem}.c").write_text(body, encoding="utf-8")
    return [outdir / f"{stem}.h", outdir / f"{stem}.c"]


def code_generator(name, elem, header=True):
    """CasADi code generator with all functions of the element type `name`."""
    cg = ca.CodeGenerator(f"{name}.c", {"with_header": header})
    for fn in elem.all():
        cg.add(fn)
    return cg


def write_element(name, elem, outdir):
    """<name>.c and <name>.h of one element type in outdir (the texts are kept with the element:
    a plugin element reused by a later build is not generated again)."""
    files = [Path(outdir) / f"{name}.c", Path(outdir) / f"{name}.h"]
    texts = elem.__dict__.setdefault("sources", {})
    if name in texts:
        for f, text in zip(files, texts[name]):
            f.write_text(text, encoding="utf-8")
    else:
        code_generator(name, elem).generate(str(outdir) + "/")
        texts[name] = [f.read_text(encoding="utf-8") for f in files]
    return files


def generate_elements(outdir):
    """Generate <type>.c/.h for every element type and fd_registry.c/.h. Returns written files."""
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    written = []
    elements = []
    for name, build in ELEMENT_BUILDERS.items():
        elem = build()
        written += write_element(name, elem, outdir)
        elements.append((name, elem))
    return written + write_registry(outdir, elements)
